  function detectLang() {
    var rawLangs = navigator.languages ? Array.from(navigator.languages) : [navigator.language || 'ru'];
    for (var i = 0; i < rawLangs.length; i++) {
      var code = (rawLangs[i] || '').toLowerCase().split('-')[0];
      if (translations[code]) {
        return code;
      }
    }
    var first = (rawLangs[0] || '').toLowerCase();
    if (first.startsWith('ru') || first.startsWith('be') || first.startsWith('uk') || first.startsWith('kk')) {
      return 'ru';
    }
    return 'en';
  }

