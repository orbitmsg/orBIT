  function applyTheme() {
    document.documentElement.classList.toggle('theme-dark', currentTheme === 'dark');
    document.documentElement.classList.toggle('theme-light', currentTheme === 'light');
    document.documentElement.style.colorScheme = currentTheme;

    var themeToggle = document.getElementById('theme-toggle');
    if (themeToggle) {
      themeToggle.textContent = dict[currentTheme === 'dark' ? 'theme_light' : 'theme_dark'];
    }
  }

  function applyTranslations() {
    document.documentElement.lang = currentLang;

    var isDownload = window.location.pathname.indexOf('download') !== -1;
    if (isDownload) {
      document.title = dict.doc_title_download || "orbitachat | скачать";
    } else {
      document.title = dict.doc_title_home || "orbitachat";
    }

    var elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      if (dict[key]) {
        el.setAttribute('aria-label', dict[key]);
      }
    });

    var languageCurrent = document.getElementById('language-current');
    if (languageCurrent) {
      languageCurrent.textContent = languageNames[currentLang];
    }
    document.querySelectorAll('.language-option').forEach(function (option) {
      option.setAttribute('aria-selected', option.getAttribute('data-language') === currentLang ? 'true' : 'false');
    });
    applyTheme();
  }

  var languagePicker = document.querySelector('.language-picker');
  var languageButton = document.getElementById('language-button');
  var languageOptions = Array.prototype.slice.call(document.querySelectorAll('.language-option'));

  function closeLanguagePicker(restoreFocus) {
    if (!languagePicker || !languageButton) return;
    languagePicker.classList.remove('is-open');
    languageButton.setAttribute('aria-expanded', 'false');
    if (restoreFocus) languageButton.focus();
  }

  function openLanguagePicker() {
    if (!languagePicker || !languageButton) return;
    languagePicker.classList.add('is-open');
    languageButton.setAttribute('aria-expanded', 'true');
    var selectedOption = languageOptions.find(function (option) {
      return option.getAttribute('data-language') === currentLang;
    });
    if (selectedOption) selectedOption.focus();
  }

  function chooseLanguage(language) {
    if (!translations[language]) return;
    currentLang = language;
      dict = translations[currentLang];
      try { localStorage.setItem('orbitachat-language', currentLang); } catch (error) {}
      applyTranslations();
    closeLanguagePicker(true);
  }

  if (languageButton) {
    languageButton.addEventListener('click', function () {
      if (languageButton.getAttribute('aria-expanded') === 'true') {
        closeLanguagePicker(false);
      } else {
        openLanguagePicker();
      }
    });
    languageButton.addEventListener('keydown', function (event) {
      if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
        event.preventDefault();
        openLanguagePicker();
      }
    });
  }

  languageOptions.forEach(function (option, index) {
    option.addEventListener('click', function () {
      chooseLanguage(option.getAttribute('data-language'));
    });
    option.addEventListener('keydown', function (event) {
      var nextIndex = index;
      if (event.key === 'ArrowDown') nextIndex = (index + 1) % languageOptions.length;
      else if (event.key === 'ArrowUp') nextIndex = (index - 1 + languageOptions.length) % languageOptions.length;
      else if (event.key === 'Home') nextIndex = 0;
      else if (event.key === 'End') nextIndex = languageOptions.length - 1;
      else if (event.key === 'Escape') {
        event.preventDefault();
        closeLanguagePicker(true);
        return;
      } else if (event.key === 'Enter' || event.key === ' ') {
        event.preventDefault();
        chooseLanguage(option.getAttribute('data-language'));
        return;
      } else if (event.key === 'Tab') {
        closeLanguagePicker(false);
        return;
      } else {
        return;
      }
      event.preventDefault();
      languageOptions[nextIndex].focus();
    });
  });

  document.addEventListener('click', function (event) {
    if (languagePicker && !languagePicker.contains(event.target)) {
      closeLanguagePicker(false);
    }
  });

  document.addEventListener('keydown', function (event) {
    if (event.key === 'Escape' && languagePicker && languagePicker.classList.contains('is-open')) {
      closeLanguagePicker(true);
    }
  });

  var themeToggle = document.getElementById('theme-toggle');
  if (themeToggle) {
    themeToggle.addEventListener('click', function () {
      currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
      try { localStorage.setItem('orbitachat-theme', currentTheme); } catch (error) {}
      applyTheme();
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyTranslations);
  } else {
    applyTranslations();
  }
